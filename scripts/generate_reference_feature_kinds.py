#!/usr/bin/env python3
"""Generate ReferenceFeatureKinds.java: which ported outputs are 'proxy' and which 'derived'.

An output is 'derived' when every observation field its formula can read is one the native
observation builder supplies (ReferenceObservation.FIELDS); otherwise some alternative input is
never available natively and the value comes from a fallback formula, which is a 'proxy'.
The table is a static fact about the code, not about any device's data.
"""
import argparse
import re
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from traceform.representation.feature_dataflow import analyze_source

EDGE = ROOT / 'android/src/org/traceform/edge'
TARGET = EDGE / 'ReferenceFeatureKinds.java'
UNOBSERVABLE_TARGET = EDGE / 'StaticallyUnobservableFeatures.java'
PRODUCER_ROOTS = ('pixel_physical', 'research/traceform/streaming', 'research/traceform/probes')


def string_array(source: str, name: str):
    block = re.search(name + r'\s*=\s*\{(.*?)\};', source, re.S).group(1)
    return re.findall(r'"([A-Za-z0-9_.]+)"', block)


def render() -> str:
    supplied = set(string_array((EDGE / 'ReferenceObservation.java').read_text(), 'FIELDS'))
    names = []
    for group in ('ReferenceUsageFeatures', 'ReferenceSignalFeatures', 'ReferenceDynamicsFeatures'):
        names += string_array((EDGE / f'{group}.java').read_text(), 'NAMES')
    flow = {item['feature']: item for item in
            analyze_source((ROOT / 'research/traceform/representation/normalizer.py').read_text())['features']}
    proxies = []
    for name in names:
        inputs = set(flow[name]['observation_inputs']) | set(flow[name]['history_observation_inputs'])
        inputs = inputs or set(flow[name]['control_observation_inputs'])
        if not inputs <= supplied:
            proxies.append(name)
    lines = ',\n        '.join('"%s"' % name for name in proxies)
    return f'''package org.traceform.edge;

import java.util.Arrays;
import java.util.HashSet;
import java.util.Set;

/**
 * GENERATED by scripts/generate_reference_feature_kinds.py - do not edit.
 * Outputs whose formula can read an observation field the native service never supplies take a
 * fallback formula there, so they are proxies; the rest are derived from supplied fields only.
 */
final class ReferenceFeatureKinds {{
    private ReferenceFeatureKinds() {{}}

    private static final Set<String> PROXY = new HashSet<>(Arrays.asList(
        {lines}));

    static String kind(String name) {{
        return PROXY.contains(name) ? "proxy" : "derived";
    }}
}}
'''


def render_unobservable() -> str:
    from traceform.representation.observability_registry import build_registry, producer_literals
    dataflow = analyze_source((ROOT / 'research/traceform/representation/normalizer.py').read_text())
    registry = build_registry(dataflow, producer_literals([ROOT / root for root in PRODUCER_ROOTS]))
    ported = set()
    for group in ('ReferenceUsageFeatures', 'ReferenceSignalFeatures', 'ReferenceDynamicsFeatures'):
        ported.update(string_array((EDGE / f'{group}.java').read_text(), 'NAMES'))
    names = [entry['feature'] for entry in registry['features']
             if entry['basis'] == 'static_no_producer' and entry['feature'] not in ported]
    lines = ',\n        '.join('"%s"' % name for name in names)
    return f'''package org.traceform.edge;

import java.util.Arrays;
import java.util.HashSet;
import java.util.Set;

/**
 * GENERATED by scripts/generate_reference_feature_kinds.py - do not edit.
 * Outputs not supplied by the ported engine and with no input producer in the acquisition code.
 * The native service records missing features with this reason.
 */
final class StaticallyUnobservableFeatures {{
    private StaticallyUnobservableFeatures() {{}}

    private static final Set<String> NAMES = new HashSet<>(Arrays.asList(
        {lines}));

    static boolean contains(String name) {{
        return NAMES.contains(name);
    }}

    /** Why a feature the sample did not supply is missing. */
    static String missingReason(String name) {{
        return NAMES.contains(name) ? "unobservable_no_producer_in_acquisition" : "not_supplied_this_sample";
    }}
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the checked-in file is out of date')
    args = parser.parse_args()
    outputs = {TARGET: render(), UNOBSERVABLE_TARGET: render_unobservable()}
    if args.check:
        raise SystemExit(0 if all(path.exists() and path.read_text() == text for path, text in outputs.items()) else 1)
    for path, text in outputs.items():
        path.write_text(text)


if __name__ == '__main__':
    main()
